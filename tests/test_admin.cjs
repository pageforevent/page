const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const context = vm.createContext({Intl, Date, URL});
vm.runInContext(fs.readFileSync(path.join(__dirname, '../site-config.js'), 'utf8'), context);
const rules = vm.runInContext('SiteConfig', context);
const expired = {title:'coupon',link:'https://example.com',validUntil:'2026-10-11'};
assert.equal(rules.status(expired, new Date('2026-10-14T15:00:00Z')), '종료');
assert.equal(rules.status({...expired, enabled:false}), '사용 안 함');
assert.equal(rules.status({...expired, validUntil:'',validFrom:'2026-11-01'},new Date('2026-10-15T00:00:00Z')), '예약');
assert.equal(rules.status({...expired, validUntil:''}), '진행 중');
assert.equal(rules.offers({primaryOffer:expired,secondaryOffer:expired}).length,2);
assert.equal(rules.offers({offers:[],primaryOffer:expired}).length,0);
assert.equal(rules.settings({}).intro,true);
assert.equal(rules.settings({settings:{intro:false}}).intro,false);
assert.equal(rules.safeLink('javascript:alert(1)'), '');
assert.equal(rules.safeLink('https://example.com'), 'https://example.com/');
assert.equal(rules.couponMode({source:'monthly'}),'auto');
assert.equal(rules.couponMode({source:'sports',manualOverride:true}),'manual');
assert.equal(rules.couponMode({source:'manual',manualOverride:false}),'manual');
assert.equal(rules.imageSource('media/banner.webp'),'media/banner.webp');
assert.equal(rules.imageSource('media/../admin.js'),'');
assert.equal(rules.imageSource('javascript:alert(1)'),'');
const base = {title:'old',offers:[{id:'a',title:'old',validUntil:'2026-10-11'},{id:'b',title:'second'}]};
const local = structuredClone(base); local.title='manual';
const remote = structuredClone(base); remote.offers[0].validUntil='2026-11-01';
const merged = rules.merge(base,local,remote);
assert.equal(merged.title,'manual');
assert.equal(merged.offers[0].validUntil,'2026-11-01');
local.offers[0].title='my coupon';
assert.equal(rules.merge(base,local,remote).offers[0].title,'my coupon');
remote.offers[0].title='other coupon';
assert.throws(() => rules.merge(base,local,remote), /같은 항목/);
const removed = structuredClone(base); removed.offers.pop();
assert.equal(rules.merge(base,removed,base).offers.length,1);
const edited = structuredClone(base); edited.offers[1].title='changed';
assert.throws(() => rules.merge(base,removed,edited), /같은 항목/);
console.log('Admin statuses, migration, settings, safe links, and concurrent-save merges passed.');
